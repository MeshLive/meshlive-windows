"""Generates src/ui/android_icons.rs from the Android app's VectorDrawables."""
import re, sys, os
# Usage: python scripts/gen_android_icons.py <meshlive-android checkout>/app/src/main/res/drawable
if len(sys.argv) != 2:
    sys.exit('usage: gen_android_icons.py <path to the Android app res/drawable folder>')
SRC = sys.argv[1]
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'ui', 'android_icons.rs')
NAMES = ['ic_live', 'ic_call', 'ic_group', 'ic_settings', 'ic_videocam', 'ic_videocam_off', 'ic_radio', 'ic_person',
         'ic_person_add', 'ic_verified_user', 'ic_info', 'ic_chevron_right', 'ic_arrow_back', 'ic_close', 'ic_check',
         'ic_check_circle', 'ic_mic', 'ic_mic_off', 'ic_camera_switch', 'ic_stop', 'ic_call_end', 'ic_lock',
         'ic_warning', 'ic_volume_up', 'ic_expand_more', 'ic_bluetooth', 'ic_pause']

def attr(text, name, default=None):
    m = re.search(r'android:' + name + r'="([^"]*)"', text)
    return m.group(1) if m else default

out = ['//! Generated by gen_icons.py from the Android app\'s VectorDrawables',
       '//! (app/src/main/res/drawable, Material Symbols Rounded, Apache-2.0, and the',
       '//! app\'s own drawings; see THIRD_PARTY_NOTICES.md). Do not edit by hand.',
       '',
       'pub struct VectorPath {',
       '    pub data: &\'static str,',
       '    pub fill: bool,',
       '    pub even_odd: bool,',
       '    /// Stroke width in viewport units (0: no stroke).',
       '    pub stroke: f32,',
       '}',
       'pub struct VectorIcon {',
       '    pub name: &\'static str,',
       '    pub viewport: (f32, f32),',
       '    pub translate: (f32, f32),',
       '    pub paths: &\'static [VectorPath],',
       '}',
       '']
for name in NAMES:
    x = open(os.path.join(SRC, name + '.xml'), encoding='utf-8').read()
    vw = float(attr(x, 'viewportWidth')); vh = float(attr(x, 'viewportHeight'))
    g = re.search(r'<group([^>]*)>', x)
    tx = float(attr(g.group(1), 'translateX', '0')) if g else 0.0
    ty = float(attr(g.group(1), 'translateY', '0')) if g else 0.0
    assert x.count('<group') <= 1, name
    paths = []
    for m in re.finditer(r'<path(.*?)/>', x, re.S):
        a = m.group(1)
        data = attr(a, 'pathData')
        fill_color = attr(a, 'fillColor', '#00000000')
        fill = not (len(fill_color) == 9 and fill_color[1:3] == '00')
        stroke_color = attr(a, 'strokeColor')
        stroke = float(attr(a, 'strokeWidth', '0')) if stroke_color else 0.0
        even = attr(a, 'fillType') == 'evenOdd'
        assert '"' not in data and '\\' not in data
        paths.append(f'        VectorPath {{ data: "{data}", fill: {str(fill).lower()}, even_odd: {str(even).lower()}, stroke: {stroke:.3f} }},')
    const = name.upper()
    out.append(f'pub const {const}: VectorIcon = VectorIcon {{')
    out.append(f'    name: "{name}",')
    out.append(f'    viewport: ({vw:.3f}, {vh:.3f}),')
    out.append(f'    translate: ({tx:.3f}, {ty:.3f}),')
    out.append('    paths: &[')
    out.extend(paths)
    out.append('    ],')
    out.append('};')
out.append('')
out.append('#[cfg(test)]')
out.append('pub const ALL: &[&VectorIcon] = &[' + ', '.join('&' + n.upper() for n in NAMES) + '];')
open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
print('ok', len(NAMES))
